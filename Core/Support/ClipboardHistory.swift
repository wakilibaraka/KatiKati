import Foundation

/// One remembered text copy (Phase 7A-P4). Text only, kept in memory only: the history is never written to disk.
struct ClipEntry: Equatable, Identifiable, Sendable {
    let id: UUID
    var text: String
    var pinned: Bool
    var date: Date

    init(id: UUID = UUID(), text: String, pinned: Bool = false, date: Date = Date()) {
        self.id = id
        self.text = text
        self.pinned = pinned
        self.date = date
    }
}

/// 55g: age-based retention. Pinned entries never expire, and `days == 0` means keep everything, which is
/// the default. The history is in memory only, so this never touches the disk.
enum ClipboardRetention {
    static func prune(_ entries: [ClipEntry], now: Date = Date(), days: Int) -> [ClipEntry] {
        guard days > 0 else { return entries }
        let cutoff = now.addingTimeInterval(-Double(days) * 86_400)
        return entries.filter { $0.pinned || $0.date >= cutoff }
    }
}

/// Clipboard history rules. Normalisation, case-insensitive-prefix "growing dictation" merge and the one-line
/// preview follow Hop's clipboard module (MIT, NOTICE §9).
struct ClipboardHistory: Equatable, Sendable {
    static let maxLength = 20_000
    static let maxUnpinned = 50
    static let previewLength = 160
    /// Pasteboard types that mark a copy as secret or machine-made (nspasteboard.org); such copies are never recorded.
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    private(set) var entries: [ClipEntry] = []

    static func shouldRecord(types: [String]) -> Bool { Set(types).isDisjoint(with: ignoredTypes) }

    /// Remembers `raw` at the top. Blank text is ignored; an identical entry moves up (keeping its pin); text that
    /// merely extends or shortens the newest entry replaces it (dictation, typing-ahead selections).
    mutating func remember(_ raw: String, now: Date = Date()) {
        let text = String(raw.prefix(Self.maxLength)).trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty else { return }
        let key = text.lowercased()
        if let first = entries.first, !first.pinned {
            let firstKey = first.text.lowercased()
            if firstKey == key {
                entries[0].text = text
                return
            }
            if key.hasPrefix(firstKey) || firstKey.hasPrefix(key) {
                entries[0].text = text
                entries[0].date = now
                return
            }
        }
        var pinned = false
        if let i = entries.firstIndex(where: { $0.text.lowercased() == key }) {
            pinned = entries[i].pinned
            entries.remove(at: i)
        }
        entries.insert(ClipEntry(text: text, pinned: pinned, date: now), at: 0)
        prune()
    }

    mutating func togglePin(_ id: UUID) {
        guard let i = entries.firstIndex(where: { $0.id == id }) else { return }
        entries[i].pinned.toggle()
        prune()
    }

    mutating func remove(_ id: UUID) { entries.removeAll { $0.id == id } }

    /// 55g: drop unpinned entries older than `days`; 0 keeps everything. Pinned entries are never old.
    mutating func prune(olderThanDays days: Int, now: Date = Date()) {
        entries = ClipboardRetention.prune(entries, now: now, days: days)
    }

    mutating func clear(keepingPinned: Bool = true) { entries = keepingPinned ? entries.filter(\.pinned) : [] }

    /// Pinned entries first (newest first within), then the rest newest first.
    var displayOrder: [ClipEntry] { entries.filter(\.pinned) + entries.filter { !$0.pinned } }

    private mutating func prune() {
        var unpinned = 0
        entries = entries.filter { entry in
            if entry.pinned { return true }
            unpinned += 1
            return unpinned <= Self.maxUnpinned
        }
    }

    /// First `previewLength` characters on one line; newlines and tabs collapse to a single space.
    static func previewLine(_ text: String) -> String {
        var line = ""
        var spaceOwed = false
        for ch in text {
            if ch.isNewline || ch == "\t" { spaceOwed = !line.isEmpty; continue }
            if spaceOwed { line.append(" "); spaceOwed = false; if line.count >= previewLength { break } }
            line.append(ch)
            if line.count >= previewLength { break }
        }
        return line.trimmingCharacters(in: .whitespaces)
    }
}
