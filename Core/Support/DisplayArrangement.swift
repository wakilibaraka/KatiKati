import CoreGraphics
import Foundation

/// One display's place in a saved arrangement. The key is the display's UUID, never its index in
/// `NSScreen.screens`: an index changes when a panel is unplugged, and a preset that reapplies by index
/// would rearrange the wrong screen.
struct DisplayArrangementEntry: Codable, Equatable, Sendable {
    let displayKey: String
    /// Quartz display coordinates (top-left origin), which is what `CGConfigureDisplayOrigin` takes.
    let originX: Double
    let originY: Double
}

/// A named set of display positions.
struct DisplayArrangement: Codable, Equatable, Sendable, Identifiable {
    let id: UUID
    /// Shown verbatim in the menu; generated by the caller ("Arrangement 2"), not a localized key.
    let name: String
    let entries: [DisplayArrangementEntry]

    init(id: UUID = UUID(), name: String, entries: [DisplayArrangementEntry]) {
        self.id = id
        self.name = name
        self.entries = entries
    }
}

/// The geometry decisions a preset needs, kept pure: one flip between the two coordinate spaces, and the
/// refusal to apply a preset that no longer describes this Mac's displays.
enum DisplayArrangementGeometry {
    /// Cocoa frame → Quartz origin.
    ///
    /// Cocoa measures y upward from the primary display's bottom-left; Quartz measures it downward from
    /// the primary's top-left. The flip therefore uses the *primary's* height, not the target screen's —
    /// using the screen's own height is the classic way to send a second display to a distant corner.
    static func quartzOrigin(cocoaFrame: CGRect, primaryMaxY: CGFloat) -> CGPoint {
        CGPoint(x: cocoaFrame.minX, y: primaryMaxY - cocoaFrame.maxY)
    }

    static func entry(displayKey: String, cocoaFrame: CGRect, primaryMaxY: CGFloat) -> DisplayArrangementEntry {
        let origin = quartzOrigin(cocoaFrame: cocoaFrame, primaryMaxY: primaryMaxY)
        return DisplayArrangementEntry(displayKey: displayKey,
                                       originX: Double(origin.x),
                                       originY: Double(origin.y))
    }

    /// Keeps the first entry per display, so a repeated screen cannot fight itself during an apply.
    static func normalized(_ entries: [DisplayArrangementEntry]) -> [DisplayArrangementEntry] {
        var seen = Set<String>()
        return entries.filter { seen.insert($0.displayKey).inserted }
    }

    /// How many of the preset's displays are connected right now.
    static func matchCount(_ arrangement: DisplayArrangement, liveKeys: Set<String>) -> Int {
        arrangement.entries.filter { liveKeys.contains($0.displayKey) }.count
    }

    /// A preset applies only when *every* display it names is connected. Applying the remainder would
    /// leave the disconnected screen's neighbour in a position nobody chose.
    static func isComplete(_ arrangement: DisplayArrangement, liveKeys: Set<String>) -> Bool {
        !arrangement.entries.isEmpty && arrangement.entries.allSatisfy { liveKeys.contains($0.displayKey) }
    }
}

/// Small list persistence; the presets are a preference, not app state.
enum DisplayArrangementStore {
    static let defaultsKey = "com.katikati.display.arrangements"

    static func load(defaults: UserDefaults = .standard) -> [DisplayArrangement] {
        guard let data = defaults.data(forKey: defaultsKey) else { return [] }
        return (try? JSONDecoder().decode([DisplayArrangement].self, from: data)) ?? []
    }

    static func save(_ arrangements: [DisplayArrangement], defaults: UserDefaults = .standard) {
        guard let data = try? JSONEncoder().encode(arrangements) else { return }
        defaults.set(data, forKey: defaultsKey)
    }
}
